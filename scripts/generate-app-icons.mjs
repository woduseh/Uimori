import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { fileURLToPath } from 'node:url';

// Small tabs use the simplified mark; installed icons retain the detailed halo inlays.
const favicon = await readFile(new URL('../web/public/icons/halo-small.svg', import.meta.url));
const source = await readFile(new URL('../web/public/icons/halo.svg', import.meta.url));
const publicRoot = new URL('../web/public/', import.meta.url);
const contents = (svg) =>
  svg
    .toString()
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '');
await writeFile(
  new URL('favicon.svg', publicRoot),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 350 350" fill="none">
  <!-- Generated by scripts/generate-app-icons.mjs from the two halo source SVGs. -->
  <style>.small{display:none}@media(max-width:32px){.detail{display:none}.small{display:inline}}</style>
  <g class="detail">${contents(source)}</g>
  <g class="small" transform="scale(5.46875)">${contents(favicon)}</g>
</svg>
`
);
for (const [file, size] of [
  ['icons/favicon-16.png', 16],
  ['icons/favicon-32.png', 32],
  ['icons/favicon-48.png', 48],
  ['favicon.png', 64],
  ['icons/app-192.png', 192],
  ['icons/app-512.png', 512],
  ['icons/apple-touch-icon.png', 180],
]) {
  await sharp(size <= 32 ? favicon : source, { density: 192 })
    .resize(size, size)
    .png()
    .toFile(fileURLToPath(new URL(file, publicRoot)));
}

// The complete seal fits inside the maskable icon's central 80% safe circle.
const mark = await sharp(source, { density: 192 }).resize(400, 400).png().toBuffer();
await sharp({ create: { width: 512, height: 512, channels: 4, background: '#14141b' } })
  .composite([{ input: mark, gravity: 'centre' }])
  .png()
  .toFile(fileURLToPath(new URL('icons/app-maskable-512.png', publicRoot)));
