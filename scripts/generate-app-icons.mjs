import { readFile, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { fileURLToPath } from 'node:url';

// Tiny tabs use a reduced seal; the full mark keeps its thin concentric strokes.
const tiny = await readFile(new URL('../web/public/icons/halo-tiny.svg', import.meta.url));
const compact = await readFile(new URL('../web/public/icons/halo-small.svg', import.meta.url));
const detailed = await readFile(new URL('../web/public/icons/halo.svg', import.meta.url));
const publicRoot = new URL('../web/public/', import.meta.url);

const stripBackground = (svg) => svg.toString().replace(/<rect[^>]*\/>\s*/, '');
const contents = (svg) =>
  svg
    .toString()
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '');

// The navigation logo shares the compact mark, but has a transparent background.
await writeFile(new URL('icons/halo-mark.svg', publicRoot), stripBackground(compact));

// SVG favicons use the appropriate simplified seal when rendered at small dimensions.
await writeFile(
  new URL('favicon.svg', publicRoot),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 350 350" fill="none">
  <!-- Generated by scripts/generate-app-icons.mjs from the halo source SVGs. -->
  <style>.compact,.tiny{display:none}@media(max-width:32px){.detailed{display:none}.compact{display:inline}}@media(max-width:16px){.compact{display:none}.tiny{display:inline}}</style>
  <g class="detailed">${contents(detailed)}</g>
  <g class="compact" transform="scale(5.46875)">${contents(compact)}</g>
  <g class="tiny" transform="scale(5.46875)">${contents(tiny)}</g>
</svg>
`
);

for (const [file, size, source] of [
  ['icons/favicon-16.png', 16, tiny],
  ['icons/favicon-32.png', 32, compact],
  ['icons/favicon-48.png', 48, detailed],
  ['favicon.png', 64, detailed],
  ['icons/app-192.png', 192, detailed],
  ['icons/app-512.png', 512, detailed],
  ['icons/apple-touch-icon.png', 180, detailed],
]) {
  await sharp(source, { density: 192 })
    .resize(size, size)
    .png()
    .toFile(fileURLToPath(new URL(file, publicRoot)));
}

// Keep the entire mark inside the maskable icon's safe area.
const mark = await sharp(detailed, { density: 192 }).resize(400, 400).png().toBuffer();
await sharp({ create: { width: 512, height: 512, channels: 4, background: '#14141b' } })
  .composite([{ input: mark, gravity: 'centre' }])
  .png()
  .toFile(fileURLToPath(new URL('icons/app-maskable-512.png', publicRoot)));
