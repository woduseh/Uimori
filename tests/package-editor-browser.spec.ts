  const library = page.getByTestId('library-panel');
  await expect(library.getByRole('tab')).toHaveText(['봇', '페르소나', '모듈', '프롬프트']);
  await expect(library.getByText('이전 자료',{exact:true})).toHaveCount(0);
  for(const name of ['로어','창작 프리셋','작가 설정','창작 스킬','명칭집'])await expect(library.getByRole('button',{name,exact:true})).toHaveCount(0);
