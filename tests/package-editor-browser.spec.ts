  await library.getByRole('tab',{name:'봇',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);await page.screenshot({path:info.outputPath('package-library-mobile.png')});
  await library.getByRole('button', { name: '새로 만들기', exact: true }).first().click();
  await expect(library.getByLabel('자료 종류',{exact:true}).locator('option')).toHaveText(['봇','페르소나','모듈']);
  await expect(library.getByLabel('관련 자료 검색',{exact:true})).toHaveCount(0);
